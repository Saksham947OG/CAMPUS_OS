/**
 * Route registry — the single place that says which destinations exist and how honest they are.
 *
 *  live        fully operational feature route (Home, Calendar, Notifications inbox, Settings)
 *  devStub     approved feature that is being built; page says so plainly and links to its spec
 *  comingLater not an approved feature in the current scope; page says so plainly
 *
 * A route's status is never faked: a test asserts every non-live page states its status.
 */
export type RouteStatus = 'live' | 'devStub' | 'comingLater'
export type NavSlot = 'sidebar' | 'utility' | 'hidden'

export interface RouteDef {
  id: string
  path: string
  label: string
  /** Shorter label for the mobile bottom nav, where width is tight. */
  shortLabel?: string
  icon: LucideIcon
  status: RouteStatus
  slot: NavSlot
  /** Mobile bottom navigation: 'primary' tabs, otherwise reachable via More. */
  mobile: 'primary' | 'more'
  summary: string
  /** Feature registry IDs this destination will eventually serve (docs/FEATURE_REGISTRY.md). */
  registryRefs: string[]
  /** Which phase builds it, when it is an approved feature. */
  plannedPhase?: string
  /** May be chosen as a Home quick action (COS-HOME-001 §5.5). */
  quickAction?: boolean
  /** Listed as a card on the Services hub. */
  hub?: boolean
}

