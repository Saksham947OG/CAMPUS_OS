export const routeById = (id: string) => routes.find((r) => r.id === id)

const patternOf = (path: string) => new RegExp(`^${path.replace(/:[^/]+/g, '[^/]+')}$`)

/** Finds the registry entry for a concrete pathname, including parameterised paths like /orders/:orderId. */
export function matchRoute(pathname: string): RouteDef | undefined {
  return (
    routes.find((r) => r.path === pathname) ??
    routes.find((r) => r.path.includes(':') && patternOf(r.path).test(pathname))
  )
}

export const sidebarRoutes = routes.filter((r) => r.slot === 'sidebar')
export const utilityRoutes = routes.filter((r) => r.slot === 'utility')
/** Bottom-nav tabs: Home, Calendar, Services (+ a More button rendered by the shell). */
export const mobilePrimaryRoutes = routes.filter((r) => r.mobile === 'primary')
export const mobileMoreRoutes = routes.filter((r) => r.mobile === 'more' && r.slot !== 'hidden')
export const quickActionRoutes = routes.filter((r) => r.quickAction)

